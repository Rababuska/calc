function getBannerovoSquarePrice(tiers, totalM2) {
    let limits = [10, 20, 50, 100, 200, Infinity];
    for (let i = 0; i < limits.length; i++) {
        if (totalM2 <= limits[i]) return tiers[i];
    }
    return tiers[tiers.length - 1];
}

function getBannerovoConstPrice(tiers, qty) {
    if (tiers.length === 2) {
        return qty <= 4 ? tiers[0] : tiers[1];
    }
    let limits = [4, 10, 30, 100, 200, Infinity];
    for (let i = 0; i < limits.length; i++) {
        if (qty <= limits[i]) return tiers[i];
    }
    return tiers[tiers.length - 1];
}

